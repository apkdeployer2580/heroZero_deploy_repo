"""Generate the launcher icon from the game's own title logo (`/title.png` in the jar).

usage:  python -I tools_re/gen_app_icon.py <herozero.jar> <android res dir>

Writes the legacy square + round icons (mipmap-*dpi/ic_launcher*.png) and the adaptive-icon
layers (ic_launcher_foreground / _background + mipmap-anydpi-v26/*.xml).

The output is GAME ART, so it is generated at build time by build_android.ps1 and gitignored —
the repository carries the recipe, never the pixels (CLAUDE.md 규율 1).
"""
import io
import sys
import zipfile
from pathlib import Path

from PIL import Image, ImageDraw

# Legacy icon edge and adaptive-layer edge (108 dp) per density.
DENSITIES = {"mdpi": (48, 108), "hdpi": (72, 162), "xhdpi": (96, 216), "xxhdpi": (144, 324), "xxxhdpi": (192, 432)}

# The title screen's own palette: near-black above, the game's crimson below.
TOP = (12, 6, 6)
BOTTOM = (150, 10, 18)

ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools_re/gen_app_icon.py from the game's title logo. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""


def gradient(size):
    img = Image.new("RGB", (size, size))
    d = ImageDraw.Draw(img)
    for y in range(size):
        t = max(0.0, (y / max(1, size - 1) - 0.35) / 0.65)
        d.line([(0, y), (size, y)], fill=tuple(int(a + (b - a) * t) for a, b in zip(TOP, BOTTOM)))
    return img


def logo_on(canvas_size, logo, fraction):
    """`logo` scaled (integer factor, nearest — it is pixel art) to fit `fraction` of the canvas, centred."""
    out = Image.new("RGBA", (canvas_size, canvas_size), (0, 0, 0, 0))
    k = max(1, int(canvas_size * fraction / max(logo.width, logo.height)))
    scaled = logo.resize((logo.width * k, logo.height * k), Image.NEAREST)
    if scaled.width > canvas_size * fraction:  # integer factor too big: fall back to smooth
        f = canvas_size * fraction / logo.width
        scaled = logo.resize((int(logo.width * f), int(logo.height * f)), Image.LANCZOS)
    out.alpha_composite(scaled, ((canvas_size - scaled.width) // 2, (canvas_size - scaled.height) // 2))
    return out


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(2)
    jar, res = Path(sys.argv[1]), Path(sys.argv[2])
    with zipfile.ZipFile(jar) as z:
        logo = Image.open(io.BytesIO(z.read("title.png"))).convert("RGBA")

    for name, (edge, layer) in DENSITIES.items():
        d = res / f"mipmap-{name}"
        d.mkdir(parents=True, exist_ok=True)
        square = gradient(edge).convert("RGBA")
        square.alpha_composite(logo_on(edge, logo, 0.86))
        square.convert("RGB").save(d / "ic_launcher.png")
        mask = Image.new("L", (edge, edge), 0)
        ImageDraw.Draw(mask).ellipse([0, 0, edge - 1, edge - 1], fill=255)
        round_icon = Image.new("RGBA", (edge, edge), (0, 0, 0, 0))
        round_icon.paste(square, (0, 0), mask)
        round_icon.save(d / "ic_launcher_round.png")
        # Adaptive: the launcher masks to the inner 72 of 108 dp, so the logo stays inside ~60 %.
        gradient(layer).save(d / "ic_launcher_background.png")
        logo_on(layer, logo, 0.60).save(d / "ic_launcher_foreground.png")

    anydpi = res / "mipmap-anydpi-v26"
    anydpi.mkdir(parents=True, exist_ok=True)
    for n in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (anydpi / n).write_text(ADAPTIVE_XML, encoding="utf-8")
    print(f"icons written under {res}")


if __name__ == "__main__":
    main()
