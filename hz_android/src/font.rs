pub const GLYPH_W: u32 = 5;
pub const GLYPH_H: u32 = 7;
/// Advance per character, in glyph cells (one blank column between letters).
pub const ADVANCE: u32 = 6;

/// Width of `text` at `scale`, in pixels.
pub fn text_width(text: &str, scale: u32) -> u32 {
    let n = text.chars().count() as u32;
    if n == 0 { 0 } else { (n * ADVANCE - 1) * scale }
}

/// Every lit pixel of `text` with its top-left at (`x`, `y`), each glyph cell `scale` px square.
pub fn for_each_pixel(text: &str, x: i32, y: i32, scale: u32, mut f: impl FnMut(i32, i32)) {
    let s = scale.max(1) as i32;
    for (i, c) in text.chars().enumerate() {
        let Some(rows) = glyph(c) else { continue };
        let gx = x + i as i32 * ADVANCE as i32 * s;
        for (row, bits) in rows.iter().enumerate() {
            for col in 0..GLYPH_W as i32 {
                if bits & (0x10 >> col) != 0 {
                    for dy in 0..s {
                        for dx in 0..s {
                            f(gx + col * s + dx, y + row as i32 * s + dy);
                        }
                    }
                }
            }
        }
    }
}

/// Does every character of `text` have a glyph? Labels are checked with this in the tests of the
/// modules that own them.
pub fn drawable(text: &str) -> bool {
    text.chars().all(|c| glyph(c).is_some())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_label_character_has_a_glyph() {
        assert!(drawable("0123456789*#OKLR"));
        assert!(drawable("ABCDEFGHIJKLMNOPQRSTUVWXYZ -+/.%<>"));
        assert!(!drawable("가"), "Korean never goes through this font");
    }

    #[test]
    fn width_and_pixels_agree() {
        assert_eq!(text_width("OK", 2), 22);
        let mut max_x = 0;
        for_each_pixel("OK", 0, 0, 2, |x, _| max_x = max_x.max(x));
        assert!(max_x < text_width("OK", 2) as i32);
    }
}
