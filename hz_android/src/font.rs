//! A 5x7 bitmap font for the host's own labels — ASCII only: upper-case letters, digits and the
//! few symbols the controls, the settings panel and the layout editor use. Korean text in host UI
//! goes through the game's own font, never through this; a character missing here draws as a
//! blank (never as a box), so `every_label_character_has_a_glyph` checks the labels in use.

